import admin from 'firebase-admin';
import fs from 'fs';
const raw = JSON.parse(fs.readFileSync('.dev_creds.json','utf8'));
const sa = JSON.parse(raw.credentials);
if (!admin.apps.length) admin.initializeApp({ credential: admin.credential.cert(sa) });
const db = admin.firestore();
const snap = await db.collection('config').doc('general').get();
const cfg = snap.data();
const msg = cfg.messaging || {};
console.log('=== VENCIMIENTOS ===');
console.log('expirationWarningDays:', cfg.expirationWarningDays ?? msg.expirationWarningDays);
console.log('expirationReminderIntervalDays:', msg.expirationReminderIntervalDays);
console.log('repeatExpirationWarnings:', msg.repeatExpirationWarnings);
console.log('expirationRules:', JSON.stringify(cfg.expirationRules || [], null, 2));
console.log('\n=== MASCOTAS ===');
console.log('petFoodWarningDays:', msg.petFoodWarningDays ?? cfg.petFoodAlertLeadDays);
console.log('petFoodDefaultCycleDays:', cfg.petFoodDefaultCycleDays ?? cfg.petFoodCycleDays ?? 'no definido');
console.log('\n=== CUMPLEAÑOS ===');
console.log('birthdayPoints:', cfg.birthdayPoints ?? msg.birthdayPoints);
console.log('\n=== CAMPAÑAS ===');
console.log('notificationWindowStart:', msg.notificationWindowStart);
console.log('notificationWindowEnd:', msg.notificationWindowEnd);
process.exit(0);
