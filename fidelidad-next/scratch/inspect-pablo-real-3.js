import admin from 'firebase-admin';
import fs from 'fs';
const raw = JSON.parse(fs.readFileSync('.dev_creds.json','utf8'));
const sa = JSON.parse(raw.credentials);
if (!admin.apps.length) admin.initializeApp({ credential: admin.credential.cert(sa) });
const db = admin.firestore();
const userId = 'mcmZ3EOy4BZZ0pqBR4pCcKDBoQN2';
db.collection('users').doc(userId).get().then(snap => {
  const d = snap.data();
  const expirationDate = d.nextExpirationDate;
  const expirationAmount = d.nextExpirationAmount;
  const lastExpirationWarningDates = d.lastExpirationWarningDates;
  const lastBirthdayGreetingYear = d.lastBirthdayGreetingYear;
  const lastBirthdayPointsYear = d.lastBirthdayPointsYear;
  const points = d.points;
  const puntos = d.puntos;
  const nombre = d.nombre || d.name;
  console.log({ nombre, points, puntos, expirationDate, expirationAmount, lastExpirationWarningDates, lastBirthdayGreetingYear, lastBirthdayPointsYear });
  process.exit(0);
});